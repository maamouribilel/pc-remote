  await expect(page.getByRole('dialog')).toBeVisible();
  await expect.poll(() => events().filter(e => e === 'release').length).toBeGreaterThan(settingsReleases);
  await expect(page.locator('#drag')).toHaveAttribute('aria-pressed', 'false');
  await page.getByRole('button', { name: 'Close connection settings', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeHidden();
