  const pad = await page.locator('.arrow-grid').evaluate(element => {
    const rect = (key: string) => { const r = element.querySelector(`[data-key="${key}"]`)!.getBoundingClientRect(); return { x: r.x, y: r.y }; };
    return { up: rect('ArrowUp'), left: rect('ArrowLeft'), enter: rect('Enter'), right: rect('ArrowRight'), down: rect('ArrowDown') };
  });
  expect(pad.up.x).toBe(pad.enter.x); expect(pad.down.x).toBe(pad.enter.x);
  expect(pad.up.y).toBeLessThan(pad.enter.y); expect(pad.down.y).toBeGreaterThan(pad.enter.y);
  expect(pad.left.y).toBe(pad.enter.y); expect(pad.right.y).toBe(pad.enter.y);
  expect(pad.left.x).toBeLessThan(pad.enter.x); expect(pad.right.x).toBeGreaterThan(pad.enter.x);
  await downArrow.scrollIntoViewIfNeeded();
