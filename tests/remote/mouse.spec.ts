  // Network-offline errors are expected during the deliberate loss case; runtime failures are not.
  expect(errors.filter(e => !e.includes('ERR_INTERNET_DISCONNECTED') && !e.includes('WebSocket') && !e.includes('Failed to fetch'))).toEqual([]);
